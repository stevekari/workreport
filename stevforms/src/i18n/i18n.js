export function createTranslator(langCode) {
  const dict = TRANSLATIONS[langCode] || TRANSLATIONS.en;
  const fallback = TRANSLATIONS.en;
  return (key, ...args) => {
    const val = dict[key] ?? fallback[key];
    if (typeof val === "function") {
      return val(...args);
    }
    return val ?? key;
  };
}
